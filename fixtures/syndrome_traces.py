"""
fixtures/syndrome_traces.py
============================
Deterministic syndrome traces and expected correction-result oracles for
decoder replay correctness testing (test_decoder_replay.py).

In a real lab these traces would be captured from the qubit control system
or generated by a validated reference decoder.  Here they are hand-crafted
to cover:

  * TRIVIAL   — no errors; expected correction is all-zeros
  * SINGLE    — single bit-flip; expected correction targets one qubit
  * MULTI     — multiple simultaneous flips
  * DENSE     — high-density error pattern (stress the decoder)
  * LEAKAGE   — contains leakage-flag measurements (if supported)
  * EMPTY     — zero-measurement chunk (edge case)

Structure
---------
Each trace is a list of chunks.  Each chunk is a list of (qubit_id, value)
pairs — identical to what StimulusGenerator.replay_trace() expects.

The oracle maps chunk_id -> List[int] (expected correction_ops).  If the
decoder is probabilistic or approximate, the test can compare against the
oracle within a tolerance rather than requiring exact match.
"""

