# ---------------------------------------------------------------------------
# Registry — import this in tests
# ---------------------------------------------------------------------------

ALL_TRACES: List[SyndromeTrace] = [
    TRACE_TRIVIAL,
    TRACE_SINGLE_FLIP,
    TRACE_MULTI_FLIP,
    TRACE_DENSE,
    TRACE_EMPTY_CHUNK,
    TRACE_VARIABLE_DENSITY,
]

TRACE_BY_NAME: Dict[str, SyndromeTrace] = {t.name: t for t in ALL_TRACES}


def get_trace(name: str) -> SyndromeTrace:
    """Retrieve a named trace, raising KeyError if unknown."""
    if name not in TRACE_BY_NAME:
        raise KeyError(f"Unknown trace '{name}'. Available: {list(TRACE_BY_NAME)}")
    return TRACE_BY_NAME[name]


# ---------------------------------------------------------------------------
# Agreement scoring helper
# ---------------------------------------------------------------------------

def score_agreement(
    oracle: Oracle,
    results: Dict[int, List[int]],
) -> float:
    """
    Compute A = M_match / N_total.

    A chunk matches if its correction_ops list equals the oracle exactly.
    Returns 1.0 if no chunks were scored (degenerate case).
    """
    if not oracle:
        return 1.0
    matches = sum(
        1
        for cid, expected in oracle.items()
        if results.get(cid) == expected
    )
    return matches / len(oracle)
